function localizedPageUrl(locale) {
  const url = new URL("https://spark.tycheworks.com/starlight-sudoku/");
  if (locale !== "ko") url.searchParams.set("lang", locale);
  return url.toString();
}

function setMetaContent(selector, value) {
  const element = document.querySelector(selector);
  if (element) element.content = value;
}

function applySeo(locale, copy) {
  const seo = seoLocales[locale];
  const pageUrl = localizedPageUrl(locale);
  const imageUrl = `https://spark.tycheworks.com/assets/Spark/Starlight%20Sudoku/${titleImages[locale]}`;
  setMetaContent('meta[property="og:title"]', copy.pageTitle);
  setMetaContent('meta[property="og:description"]', copy.pageDescription);
  setMetaContent('meta[property="og:url"]', pageUrl);
  setMetaContent('meta[property="og:image"]', imageUrl);
  setMetaContent('meta[property="og:image:alt"]', seo.imageAlt);
  setMetaContent('meta[property="og:locale"]', seo.ogLocale);
  setMetaContent('meta[name="twitter:title"]', copy.pageTitle);
  setMetaContent('meta[name="twitter:description"]', copy.pageDescription);
  setMetaContent('meta[name="twitter:image"]', imageUrl);
  setMetaContent('meta[name="twitter:image:alt"]', seo.imageAlt);
  const canonical = document.querySelector('link[rel="canonical"]');
  if (canonical) canonical.href = pageUrl;
  const structuredData = document.querySelector("#starlight-detail-structured-data");
  if (structuredData) {
    const data = JSON.parse(structuredData.textContent);
    Object.assign(data, { name: seo.name, description: copy.pageDescription, url: pageUrl, image: imageUrl, inLanguage: seo.schemaLanguage });
    structuredData.textContent = JSON.stringify(data);
  }
}

function normalizeLocale(value) {
  const candidate = String(value || "").toLowerCase();
  if (candidate.startsWith("zh-tw") || candidate.startsWith("zh-hk") || candidate === "tw") return "zh-TW";
  if (candidate.startsWith("zh")) return "zh-CN";
  if (candidate.startsWith("ja")) return "ja";
  if (candidate.startsWith("en")) return "en";
  return "ko";
}

function applyLocale(locale, updateUrl = true) {
  const resolvedLocale = supportedLocales.includes(locale) ? locale : "ko";
  const copy = translations[resolvedLocale];

  document.documentElement.lang = resolvedLocale;
  document.title = copy.pageTitle;
  if (descriptionMeta) descriptionMeta.content = copy.pageDescription;
  applySeo(resolvedLocale, copy);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value) element.innerHTML = value;
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = copy[element.dataset.i18nAlt];
    if (value) element.alt = value;
  });

  if (titleImage) {
    titleImage.src = `../../assets/Spark/Starlight%20Sudoku/${titleImages[resolvedLocale]}`;
    titleImage.alt = copy.imageAlt;
  }

  localeButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.locale === resolvedLocale));
  });

  const landingBase = "https://starlight-sudoku.tycheworks.com/";
  landingLinks.forEach((landingLink) => {
    landingLink.href = resolvedLocale === "ko" ? landingBase : `${landingBase}?lang=${encodeURIComponent(resolvedLocale)}`;
  });
  if (privacyLink) privacyLink.href = resolvedLocale === "ko" ? "privacy/" : `privacy/?lang=${encodeURIComponent(resolvedLocale)}`;

  try { localStorage.setItem("starlight-sudoku-locale", resolvedLocale); } catch {}
  if (updateUrl) {
    const url = new URL(window.location.href);
    if (resolvedLocale === "ko") url.searchParams.delete("lang");
    else url.searchParams.set("lang", resolvedLocale);
    history.replaceState(null, "", url);
  }
}

const queryLocale = new URLSearchParams(window.location.search).get("lang");
let storedLocale = "";
try { storedLocale = localStorage.getItem("starlight-sudoku-locale") || ""; } catch {}
const initialLocale = queryLocale ? normalizeLocale(queryLocale) : normalizeLocale(storedLocale || navigator.language);
applyLocale(initialLocale, Boolean(queryLocale));

localeButtons.forEach((button) => {
  button.addEventListener("click", () => applyLocale(button.dataset.locale));
});
